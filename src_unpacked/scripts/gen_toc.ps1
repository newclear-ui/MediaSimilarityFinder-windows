#requires -Version 7.0
<#
.SYNOPSIS
  Markdown 문서의 h2 목차를 앵커 + 줄번호로 생성/갱신한다.

.DESCRIPTION
  - GitHub 앵커 규칙(github-slugger)을 구현한다. 실측 검증: progress-detail 141/141 일치.
  - 마커 사이의 목차 블록만 교체한다. 문서 본문은 건드리지 않는다.
  - 마커가 없으면 첫 `##` heading 앞에 삽입한다.
  - -Check 는 쓰지 않고, 현재 목차가 최신인지만 검사한다.

.EXAMPLE
  pwsh -NoProfile -File scripts/gen_toc.ps1 -Path docs/development-progress.ko.md
  pwsh -NoProfile -File scripts/gen_toc.ps1 -Path docs/development-progress.ko.md -Check
#>
param(
  [string[]]$Path,
  [switch]$All,
  [switch]$Check
)
$ErrorActionPreference = 'Stop'

$begin = '<!-- BEGIN TOC (generated by scripts/gen_toc.ps1) -->'
$end = '<!-- END TOC -->'

if ($All) {
  $root = Split-Path -Parent (Split-Path -Parent $PSCommandPath)
  $docsDir = Join-Path $root 'docs'
  $found = New-Object System.Collections.Generic.List[string]
  foreach ($f in (Get-ChildItem $docsDir -Recurse -Filter *.md)) {
    $head = Get-Content $f.FullName -TotalCount 15
    if ($head -contains $begin) { $found.Add($f.FullName) }
  }
  $Path = $found.ToArray()
  if ($Path.Count -eq 0) { Write-Output 'no toc files found'; exit 0 }
}
if (-not $Path -or $Path.Count -eq 0) { throw 'no -Path and no -All' }

function Get-Slug([string]$text) {
  # heading 의 표시 텍스트를 GitHub 렌더 결과와 같게 만든다
  $t = $text
  $t = [regex]::Replace($t, '!\[([^\]]*)\]\([^)]*\)', '$1')   # image -> alt
  $t = [regex]::Replace($t, '\[([^\]]*)\]\([^)]*\)', '$1')    # link -> text
  $t = [regex]::Replace($t, '`([^`]*)`', '$1')                # inline code
  $t = [regex]::Replace($t, '<[^>]+>', '')                    # html tag
  $t = $t -replace '\*\*|__|~~|\*', ''                        # emphasis markers
  $t = $t.Trim().ToLowerInvariant()

  $sb = New-Object System.Text.StringBuilder
  foreach ($ch in $t.ToCharArray()) {
    $cat = [System.Globalization.CharUnicodeInfo]::GetUnicodeCategory($ch)
    $keep = $false
    if ($ch -eq ' ' -or $ch -eq '-' -or $ch -eq '_') { $keep = $true }
    elseif ($cat -eq [System.Globalization.UnicodeCategory]::UppercaseLetter -or
            $cat -eq [System.Globalization.UnicodeCategory]::LowercaseLetter -or
            $cat -eq [System.Globalization.UnicodeCategory]::TitlecaseLetter -or
            $cat -eq [System.Globalization.UnicodeCategory]::ModifierLetter -or
            $cat -eq [System.Globalization.UnicodeCategory]::OtherLetter -or
            $cat -eq [System.Globalization.UnicodeCategory]::DecimalDigitNumber -or
            $cat -eq [System.Globalization.UnicodeCategory]::LetterNumber -or
            $cat -eq [System.Globalization.UnicodeCategory]::NonSpacingMark -or
            $cat -eq [System.Globalization.UnicodeCategory]::SpacingCombiningMark -or
            $cat -eq [System.Globalization.UnicodeCategory]::ConnectorPunctuation) { $keep = $true }
    if ($keep) { [void]$sb.Append($ch) }
  }
  return $sb.ToString().Replace(' ', '-')
}

function New-TocBlock([string[]]$lines, [bool]$isEnglish) {
  $seen = @{}
  $items = New-Object System.Collections.Generic.List[string]
  $inToc = $false
  for ($i = 0; $i -lt $lines.Count; $i++) {
    if ($lines[$i] -eq '<!-- BEGIN TOC (generated by scripts/gen_toc.ps1) -->') { $inToc = $true; continue }
    if ($lines[$i] -eq '<!-- END TOC -->') { $inToc = $false; continue }
    if ($inToc) { continue }
    if ($lines[$i] -notmatch '^##\s+(.+?)\s*$') { continue }
    $raw = $Matches[1]
    $label = $raw
    $label = [regex]::Replace($label, '!\[([^\]]*)\]\([^)]*\)', '$1')
    $label = [regex]::Replace($label, '\[([^\]]*)\]\([^)]*\)', '$1')
    $label = [regex]::Replace($label, '`([^`]*)`', '$1')
    $label = [regex]::Replace($label, '[\x00-\x1F\x7F]', '')
    $label = $label.Trim()

    $slug = Get-Slug $raw
    if ($seen.ContainsKey($slug)) {
      $n = $seen[$slug] + 1
      $seen[$slug] = $n
      $anchor = '{0}-{1}' -f $slug, $n
    } else {
      $seen[$slug] = 0
      $anchor = $slug
    }
    $items.Add(('- [{0}](#{1}) — L{2}' -f $label, $anchor, ($i + 1)))
  }

  $block = New-Object System.Collections.Generic.List[string]
  $block.Add($begin)
  $block.Add('')
  $block.Add($(if ($isEnglish) { '## Contents' } else { '## 목차' }))
  $block.Add('')
  foreach ($x in $items) { $block.Add($x) }
  $block.Add('')
  $block.Add($end)
  return $block
}

$fail = 0
foreach ($p in $Path) {
  if (-not (Test-Path $p)) { throw "not found: $p" }
  $raw = [System.IO.File]::ReadAllText($p)
  $nl = if ($raw.Contains("`r`n")) { "`r`n" } else { "`n" }
  $endsNl = $raw.EndsWith("`n")
  $lines = New-Object System.Collections.Generic.List[string]
  $lines.AddRange([System.IO.File]::ReadAllLines($p))
  $isEn = $p -match '\.en\.md$'

  $block = New-TocBlock $lines.ToArray() $isEn

  $b = -1; $e = -1
  for ($i = 0; $i -lt $lines.Count; $i++) {
    if ($lines[$i] -eq $begin) { $b = $i }
    if ($lines[$i] -eq $end) { $e = $i; break }
  }

  if ($b -ge 0 -and $e -gt $b) {
    $new = New-Object System.Collections.Generic.List[string]
    for ($i = 0; $i -lt $b; $i++) { $new.Add($lines[$i]) }
    foreach ($x in $block) { $new.Add($x) }
    for ($i = $e + 1; $i -lt $lines.Count; $i++) { $new.Add($lines[$i]) }
    $updated = $new
  } else {
    # 첫 ## heading 앞에 삽입
    $first = -1
    for ($i = 0; $i -lt $lines.Count; $i++) { if ($lines[$i] -match '^## ') { $first = $i; break } }
    if ($first -lt 0) { throw "no h2 heading in $p" }
    $at = $first
    while ($at -gt 0 -and $lines[$at - 1] -eq '') { $at-- }
    $new = New-Object System.Collections.Generic.List[string]
    for ($i = 0; $i -lt $at; $i++) { $new.Add($lines[$i]) }
    foreach ($x in $block) { $new.Add($x) }
    $new.Add('')
    $new.Add('')
    for ($i = $first; $i -lt $lines.Count; $i++) { $new.Add($lines[$i]) }

    # 목차가 삽입된 뒤의 실제 줄번호로 다시 계산해 교체한다 (2패스)
    $b2 = -1; $e2 = -1
    for ($i = 0; $i -lt $new.Count; $i++) {
      if ($new[$i] -eq $begin) { $b2 = $i }
      if ($new[$i] -eq $end) { $e2 = $i; break }
    }
    if ($b2 -lt 0 -or $e2 -le $b2) { throw "toc marker insertion failed in $p" }
    $block2 = New-TocBlock $new.ToArray() $isEn
    $final = New-Object System.Collections.Generic.List[string]
    for ($i = 0; $i -lt $b2; $i++) { $final.Add($new[$i]) }
    foreach ($x in $block2) { $final.Add($x) }
    for ($i = $e2 + 1; $i -lt $new.Count; $i++) { $final.Add($new[$i]) }
    $updated = $final
  }

  $same = ($updated.Count -eq $lines.Count)
  if ($same) {
    for ($i = 0; $i -lt $lines.Count; $i++) { if ($updated[$i] -cne $lines[$i]) { $same = $false; break } }
  }

  $leaf = Split-Path $p -Leaf
  if ($Check) {
    if ($same) { Write-Output "OK    toc up to date  $leaf  entries=$($block.Count - 4)" }
    else { Write-Output "STALE toc differs    $leaf"; $script:fail++ }
  } else {
    if ($same) {
      Write-Output "SAME  $leaf"
    } else {
      $out = ($updated -join $nl)
      if ($endsNl) { $out += $nl }
      [System.IO.File]::WriteAllText($p, $out, (New-Object System.Text.UTF8Encoding($false)))
      Write-Output "WROTE $leaf  entries=$($block.Count - 4)"
    }
  }
}
if ($Check) { if ($fail -gt 0) { exit 1 } }
